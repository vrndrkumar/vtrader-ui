import '../models/broker_model.dart';
import '../models/strategy_model.dart';
import '../../core/constants/app_constants.dart';

/// Service for handling local storage operations
class StorageService {
  static late SharedPreferences _prefs;
  static late Box<UserModel> _userBox;
  static late Box<TradeModel> _tradesBox;
  static late Box<BrokerModel> _brokersBox;
  static late Box<StrategyModel> _strategiesBox;
  static late Box<PositionModel> _positionsBox;
  static late Box<dynamic> _settingsBox;

  /// Initialize storage service
  static Future<void> init() async {
    // Initialize SharedPreferences
    _prefs = await SharedPreferences.getInstance();

    // Register Hive adapters
    _registerAdapters();

    // Open Hive boxes
    await _openBoxes();
  }

  /// Register all Hive type adapters
  static void _registerAdapters() {
    // Register model adapters (generated by hive_generator)
    // These would be generated automatically
    // Hive.registerAdapter(UserModelAdapter());
