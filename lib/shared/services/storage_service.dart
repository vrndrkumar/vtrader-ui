    // Hive.registerAdapter(OrderTypeAdapter());
    // Hive.registerAdapter(BrokerModelAdapter());
    // Hive.registerAdapter(BrokerTypeAdapter());
    // Hive.registerAdapter(BrokerSyncSettingsAdapter());
    // Hive.registerAdapter(PositionModelAdapter());
